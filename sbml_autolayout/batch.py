"""Batch runner: lay out many pathways in one go.

    uv run sbml-autolayout-batch INPUT [INPUT ...] [-o OUTDIR] [layout options]
    (or: python -m sbml_autolayout.batch ...)

INPUT can be files (.xml, .sbml, .json) or folders. A folder is scanned for such files and each
file becomes its own map. With --merge-subfolders, every subfolder of a given folder is merged into
ONE map (all SBML files in it combined), e.g. examples/my_pathway/{part1.xml, part2.xml}.

Without -o the results go to ./output/<input folder name>/ (the data folder is left untouched).
For each map OUTDIR gets NAME.sbml, NAME.svg, and NAME.escher.json, plus
  summary.csv  – one row per map: status, size, crossings, overlaps, runtime, error message
  index.html   – all SVGs side by side, to compare the results in a browser
A failing file is reported and skipped; the rest of the batch continues.
All layout options of the single-map command apply to every map (e.g. --density 1.3).
"""
from __future__ import annotations

import argparse
import csv
import html
import os
import re
import sys
import time
import traceback
from concurrent.futures import ProcessPoolExecutor

from .__main__ import add_layout_options, run

EXT = (".xml", ".sbml", ".json")
SKIP = (".layout.json", ".escher.json", ".escher.json.bak")   # .layout.json: outputs of older versions


def _is_input(path: str) -> bool:
    low = path.lower()
    return low.endswith(EXT) and not low.endswith(SKIP)


def _is_own_output(path: str) -> bool:
    """Skip files written by sbml-autolayout itself (when the output folder lies inside an input folder)."""
    if path.lower().endswith(".layout.json"):
        return True
    try:
        with open(path, "r", encoding="utf-8", errors="ignore") as fh:
            head = fh.read(4000)
    except OSError:
        return False
    return any(f"Generated by {n}" in head or f"{n}-" in head and "layout_hash" in head
               for n in ("sbml-autolayout", "metlayout"))      # metlayout: the earlier name


def collect_jobs(inputs: list[str], merge_subfolders: bool, outdir: str) -> list[tuple[str, list[str]]]:
    """-> [(name, [files])] ; one entry per map."""
    jobs: list[tuple[str, list[str]]] = []
    out_abs = os.path.abspath(outdir)
    for inp in inputs:
        if os.path.isfile(inp):
            jobs.append((_stem(inp), [inp]))
            continue
        if not os.path.isdir(inp):
            print(f"warning: {inp} not found, skipped", file=sys.stderr)
            continue
        for entry in sorted(os.listdir(inp)):
            p = os.path.join(inp, entry)
            if os.path.abspath(p) == out_abs:
                continue
            if os.path.isdir(p) and merge_subfolders:
                files = [os.path.join(p, f) for f in sorted(os.listdir(p))
                         if _is_input(f) and not f.lower().endswith(".json")]
                if files:
                    jobs.append((entry, files))
            elif os.path.isfile(p) and _is_input(p) and not _is_own_output(p):
                jobs.append((_stem(p), [p]))
    # unique names
    seen: dict[str, int] = {}
    out = []
    for name, files in jobs:
        n = seen.get(name, 0)
        seen[name] = n + 1
        out.append((name if n == 0 else f"{name}_{n + 1}", files))
    return out


def _stem(path: str) -> str:
    base = os.path.basename(path)
    for ext in (".escher.json",) + EXT:
        if base.lower().endswith(ext):
            base = base[: -len(ext)]
            break
    return re.sub(r"[^\w.-]+", "_", base) or "map"


def _one(job):
    name, files, outdir, a = job
    t0 = time.time()
    row = {"name": name, "inputs": " + ".join(files), "status": "ok", "error": ""}
    try:
        L = run(files, os.path.join(outdir, name), a, verbose=False)
        from .metrics import layout_metrics, overlap_report
        m = layout_metrics(L)
        ov = overlap_report(L)
        row.update({"metabolites": len(L.met_pos), "reactions": len(L.rxn_pos), "clones": len(L.clones),
                    "cycles": len(L.cycles), "crossings": m.get("main_edge_crossings"),
                    "overlaps": sum(len(v) for v in ov.values()),
                    "width": round(L.width), "height": round(L.height),
                    "layout_hash": L.meta.get("layout_hash", "")})
    except Exception as e:  # keep the batch going
        row["status"] = "failed"
        row["error"] = f"{type(e).__name__}: {e}"
        if getattr(a, "debug", False):
            row["error"] += "\n" + traceback.format_exc()
    row["seconds"] = round(time.time() - t0, 1)
    return row


COLUMNS = ["name", "status", "metabolites", "reactions", "clones", "cycles", "crossings", "overlaps",
           "width", "height", "seconds", "layout_hash", "inputs", "error"]


def write_index(rows: list[dict], outdir: str):
    cards = []
    for r in rows:
        if r["status"] != "ok":
            cards.append(f'<div class="card bad"><h2>{html.escape(r["name"])}</h2>'
                         f'<p>failed: {html.escape(r["error"])}</p></div>')
            continue
        n = html.escape(r["name"])
        stats = (f'{r["metabolites"]} metabolites · {r["reactions"]} reactions · {r["cycles"]} cycle(s) · '
                 f'{r["crossings"]} crossing(s) · {r["overlaps"]} overlap(s) · {r["seconds"]} s')
        cards.append(f'<div class="card"><h2>{n}</h2><p>{stats}</p>'
                     f'<a href="{n}.svg"><img src="{n}.svg" alt="{n}"></a>'
                     f'<p class="files"><a href="{n}.svg">SVG</a> · <a href="{n}.sbml">SBML</a> · '
                     f'<a href="{n}.escher.json">Escher</a></p></div>')
    page = f"""<!DOCTYPE html><html><head><meta charset="utf-8"><title>sbml-autolayout batch</title>
<style>body{{font-family:system-ui,sans-serif;margin:24px;background:#f6f7f9;color:#222}}
.grid{{display:grid;grid-template-columns:repeat(auto-fill,minmax(420px,1fr));gap:18px}}
.card{{background:#fff;border:1px solid #dde1e6;border-radius:8px;padding:12px}}
.card h2{{font-size:16px;margin:0 0 4px}} .card p{{font-size:12px;color:#555;margin:4px 0}}
.card img{{width:100%;height:420px;object-fit:contain;background:#fff}}
.bad{{border-color:#d33}} .bad p{{color:#a11}}</style></head><body>
<h1>sbml-autolayout batch – {len(rows)} map(s)</h1><div class="grid">{''.join(cards)}</div></body></html>"""
    with open(os.path.join(outdir, "index.html"), "w", encoding="utf-8") as fh:
        fh.write(page)


def main(argv=None):
    ap = argparse.ArgumentParser(prog="sbml_autolayout.batch", description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("inputs", nargs="+", help="files and/or folders")
    ap.add_argument("-o", "--outdir",
                    help="output folder (default: ./output/<name of the input folder>, so the data folder "
                         "itself is never written to)")
    ap.add_argument("--merge-subfolders", action="store_true",
                    help="each subfolder of an input folder = one merged map")
    ap.add_argument("-j", "--jobs", type=int, default=1, help="maps computed in parallel (default 1)")
    ap.add_argument("--debug", action="store_true", help="include full tracebacks for failed maps")
    add_layout_options(ap)
    a = ap.parse_args(argv)
    for inp in a.inputs:
        if not os.path.exists(os.path.expanduser(inp)):
            ap.error(f"input not found: {inp}")
    a.inputs = [os.path.expanduser(p) for p in a.inputs]
    if not a.outdir:
        if len(a.inputs) == 1:
            name = os.path.basename(os.path.normpath(a.inputs[0])) if os.path.isdir(a.inputs[0]) \
                else _stem(a.inputs[0])
        else:
            name = "batch"
        a.outdir = os.path.join("output", name)
    a.outdir = os.path.expanduser(a.outdir)

    os.makedirs(a.outdir, exist_ok=True)
    jobs = collect_jobs(a.inputs, a.merge_subfolders, a.outdir)
    if not jobs:
        ap.error("no input files found (.xml, .sbml, .json)")
    print(f"{len(jobs)} map(s) -> {a.outdir}")
    work = [(name, files, a.outdir, a) for name, files in jobs]
    rows = []
    if a.jobs > 1:
        with ProcessPoolExecutor(max_workers=a.jobs) as ex:
            for row in ex.map(_one, work):
                rows.append(row)
                _report(row)
    else:
        for w in work:
            row = _one(w)
            rows.append(row)
            _report(row)

    with open(os.path.join(a.outdir, "summary.csv"), "w", newline="", encoding="utf-8") as fh:
        wr = csv.DictWriter(fh, fieldnames=COLUMNS, extrasaction="ignore")
        wr.writeheader()
        wr.writerows(rows)
    write_index(rows, a.outdir)
    ok = sum(r["status"] == "ok" for r in rows)
    print(f"done: {ok}/{len(rows)} ok — see {os.path.join(a.outdir, 'index.html')} and summary.csv")
    return 0 if ok == len(rows) else 1


def _report(r):
    if r["status"] == "ok":
        print(f"  ok      {r['name']:<32} {r['metabolites']:>3} met {r['reactions']:>3} rxn  "
              f"{r['crossings']} crossing(s)  {r['overlaps']} overlap(s)  {r['seconds']} s")
    else:
        print(f"  FAILED  {r['name']:<32} {r['error'].splitlines()[0]}")


if __name__ == "__main__":
    sys.exit(main())
